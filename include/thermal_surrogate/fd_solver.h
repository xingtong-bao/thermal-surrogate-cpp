// thermal_surrogate/fd_solver.h -- in-process reference: a 2-D steady-state finite-difference solver
//
// What it models (and what it does not)
//   Two terms, both proportional to power (so the reference has the physical
//   gain of 1 that the surrogate lacks, S2b.1):
//     T(x,y) = T_ambient + P_total * (alpha * r_convec + beta)        lumped sink
//              + T_local(x,y)                                          die spreading
//   where T_local solves, on the 64x64 grid with insulated edges,
//     div( k t grad T_local ) + q'' - g_v T_local = 0
//   with q'' = chiplet power / footprint area (W/m^2), k from the
//   local_thermal_k channel, t an effective conducting thickness and g_v an
//   effective vertical conductance per area (W/m^2/K) into the sink.
//   The dataset was generated by a multi-layer RC network (HotSpot); the
//   channels h_w_m2k and r_convec_k_per_w turn out to encode the same sink
//   (h = 1 / (r * 0.0282 m^2) in every sample), and the observed minimum
//   temperature rise follows P*(alpha*r + beta) rather than P*r alone. The
//   four scalars (alpha, beta, t, g_v) are calibrated once on 20 TRAINING
//   samples (never the test split) and stored in models/fd_solver_params.json.
//   Accuracy against the dataset truth is measured in S5.2 and reported as
//   is: this is a physics-consistent but reduced-order reference.
//
// Numerics: successive over-relaxation (SOR), red-black ordering, stops when
// the max update falls below `tol` K or after `max_iter` sweeps.
//
// Parallelism (S9.1): a plain Gauss-Seidel/SOR sweep is sequential, because
// cell i reads the value cell i-1 produced a moment ago. Red-black ordering
// colours the grid like a chessboard: every neighbour of a red cell is black,
// so all red cells can be updated at once from black values, then all black
// cells from red values. Each half-sweep is a parallel loop over rows (OpenMP
// when the build has it, serial otherwise). Because a cell only ever reads
// cells of the other colour, the result does not depend on how rows are
// distributed over threads: 1 thread and N threads give bit-identical fields
// and the same iteration count (tests/test_fd_solver.cpp checks this). The
// only cross-thread value is the max |update|, and max is order-independent.
// Measured on an M4 (docs/results/sor_scaling_notes.md): 2.7x at 512^2 with 4
// threads, but slower than serial at the 64^2 contract grid, where a half-sweep
// is ~2.5 us of work; hence `threads` defaults to 1.
#pragma once

#include <cstddef>
#include <span>
#include <string>
#include <vector>

#include "thermal_surrogate/backend.h"
#include "thermal_surrogate/types.h"

namespace thermal_surrogate {

struct FdSolverParams {
  double thickness_m = 1e-3;     // effective conducting thickness t (calibrated)
  double g_v_w_m2k = 1000.0;     // effective vertical conductance per area into the sink (calibrated)
  double alpha = 1.0;            // sink rise = P_total * (alpha * r_convec + beta) (calibrated)
  double beta = 0.0;
  double omega = 1.8;            // SOR relaxation factor
  double tol = 1e-4;             // stop when max |dT| per sweep < tol (K)
  int max_iter = 20000;
  int threads = 1;               // 1 = serial; N = OpenMP threads (one team for the whole solve); 0 = all hardware threads
  bool dynamic_schedule = false; // row scheduling, see SorSchedule
};

struct FdSolveStats {
  int iterations = 0;
  double final_update_K = 0.0;
  bool converged = false;
};

// Solve one contract tensor into `field`. Returns Ok, ShapeMismatch or ReferenceFailed.
//
// Buffers are std::span (C++20, S10.1): a pointer and a length travel together,
// so the solver can check them instead of trusting a comment. `input` must hold
// exactly kInputSize floats and `field` exactly kCells floats, otherwise the
// call returns ShapeMismatch and touches nothing. A std::vector, a std::array
// or a slice of a larger batch (std::span(batch).subspan(i * kInputSize,
// kInputSize)) all convert without a copy.
Status fd_solve(std::span<const float> input, const FdSolverParams& p, std::span<float> field,
                FdSolveStats* stats = nullptr) noexcept;

// ---- grid-generic SOR core ------------------------------------------------------
// fd_solve() builds one of these from the 64x64 contract tensor; bench_sor_scaling
// builds them at 64^2 .. 512^2 to measure thread scaling. Same code path either way.
struct SorGrid {
  std::size_t nx = 0, ny = 0;    // cells; cell (x, y) is index x * ny + y
  std::vector<double> q;         // heat source per cell, W/m^2
  std::vector<double> kx;        // conductance to the +x neighbour, W/K (0 on the last column)
  std::vector<double> ky;        // conductance to the +y neighbour, W/K (0 on the last row)
  double area = 0.0;             // cell area, m^2
  double g_sink = 0.0;           // conductance per cell into the sink, W/K
  double t_sink = 0.0;           // sink temperature, K
  std::size_t cells() const { return nx * ny; }
};

// One red-black sweep (red half-sweep, then black) in place; returns max |update| in K.
// `threads` as in FdSolverParams::threads. T must hold g.cells() values; on any
// other length nothing is touched and the result is NaN (S10.1: the span
// carries its length, so the check costs one comparison).
//
// T is std::span<double> rather than std::vector<double>&: the sweep reads and
// writes values but never resizes, so any contiguous buffer will do (a
// vector, a pool slice, a buffer owned by a caller in another language).
double sor_sweep(const SorGrid& g, double omega, int threads, std::span<double> T) noexcept;

// How rows are handed to threads. Static: equal contiguous blocks (best when all
// cores are alike). Dynamic: chunks of 4 rows on demand (better on
// performance + efficiency core mixes, where a static split waits for the
// slowest core). Either way the result is bit-identical.
enum class SorSchedule { Static, Dynamic };

// Sweep until max |update| < tol or max_iter sweeps. T holds the initial guess on
// entry (g.cells() values) and the solution on return; on a wrong length nothing
// is touched and the stats say 0 iterations, not converged. With threads > 1 and
// OpenMP, one parallel region spans the whole iteration (two barriers per sweep).
FdSolveStats sor_solve(const SorGrid& g, double omega, double tol, int max_iter, int threads, std::span<double> T,
                       SorSchedule sched = SorSchedule::Static) noexcept;

// True when the library was built with OpenMP (threads > 1 has an effect).
bool fd_solver_has_openmp() noexcept;

FdSolverParams load_fd_params(const std::string& json_path);   // throws on missing file

class FdSolverBackend final : public ISolverBackend {
 public:
  explicit FdSolverBackend(FdSolverParams p) : params_(p) {}
  Source source() const override { return Source::ReferenceInProcess; }
  std::string name() const override { return "fd_solver"; }
  void solve(const Input& in, Output& out) noexcept override;
  const FdSolverParams& params() const { return params_; }

 private:
  FdSolverParams params_;
};

}  // namespace thermal_surrogate
