// thermal_surrogate/fd_solver.h -- in-process reference: a 2-D steady-state finite-difference solver
//
// What it models (and what it does not)
//   Two terms, both proportional to power (so the reference has the physical
//   gain of 1 that the surrogate lacks, S2b.1):
//     T(x,y) = T_ambient + P_total * (alpha * r_convec + beta)        lumped sink
//              + T_local(x,y)                                          die spreading
//   where T_local solves, on the 64x64 grid with insulated edges,
//     div( k t grad T_local ) + q'' - g_v T_local = 0
//   with q'' = chiplet power / footprint area (W/m^2), k from the
//   local_thermal_k channel, t an effective conducting thickness and g_v an
//   effective vertical conductance per area (W/m^2/K) into the sink.
//   The dataset was generated by a multi-layer RC network (HotSpot); the
//   channels h_w_m2k and r_convec_k_per_w turn out to encode the same sink
//   (h = 1 / (r * 0.0282 m^2) in every sample), and the observed minimum
//   temperature rise follows P*(alpha*r + beta) rather than P*r alone. The
//   four scalars (alpha, beta, t, g_v) are calibrated once on 20 TRAINING
//   samples (never the test split) and stored in models/fd_solver_params.json.
//   Accuracy against the dataset truth is measured in S5.2 and reported as
//   is: this is a physics-consistent but reduced-order reference.
//
// Numerics: successive over-relaxation (SOR), red-black ordering, stops when
// the max update falls below `tol` K or after `max_iter` sweeps.
#pragma once

#include <cstddef>
#include <string>

#include "thermal_surrogate/backend.h"
#include "thermal_surrogate/types.h"

namespace thermal_surrogate {

struct FdSolverParams {
  double thickness_m = 1e-3;     // effective conducting thickness t (calibrated)
  double g_v_w_m2k = 1000.0;     // effective vertical conductance per area into the sink (calibrated)
  double alpha = 1.0;            // sink rise = P_total * (alpha * r_convec + beta) (calibrated)
  double beta = 0.0;
  double omega = 1.8;            // SOR relaxation factor
  double tol = 1e-4;             // stop when max |dT| per sweep < tol (K)
  int max_iter = 20000;
};

struct FdSolveStats {
  int iterations = 0;
  double final_update_K = 0.0;
  bool converged = false;
};

// Solve one contract tensor into `field` (kCells floats). Returns Ok or ReferenceFailed.
Status fd_solve(const float* input, const FdSolverParams& p, float* field, FdSolveStats* stats = nullptr) noexcept;

FdSolverParams load_fd_params(const std::string& json_path);   // throws on missing file

class FdSolverBackend final : public ISolverBackend {
 public:
  explicit FdSolverBackend(FdSolverParams p) : params_(p) {}
  Source source() const override { return Source::ReferenceInProcess; }
  std::string name() const override { return "fd_solver"; }
  void solve(const Input& in, Output& out) noexcept override;
  const FdSolverParams& params() const { return params_; }

 private:
  FdSolverParams params_;
};

}  // namespace thermal_surrogate
